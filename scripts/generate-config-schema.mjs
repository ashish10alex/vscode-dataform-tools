#!/usr/bin/env node
// Generates src/configBlock/schema.generated.ts from the configs.proto shipped with @dataform/core.
//
// Usage: node scripts/generate-config-schema.mjs [coreVersion]   (defaults to the latest published version)

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(repoRoot, "src", "configBlock", "schema.generated.ts");
const requestedVersion = process.argv[2] ?? "latest";

const npm = process.platform === "win32" ? "npm.cmd" : "npm";
const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "dataform-core-"));
const packOutput = execFileSync(npm, ["pack", `@dataform/core@${requestedVersion}`, "--json"], { cwd: tmpDir, encoding: "utf8" });
const { filename, version } = JSON.parse(packOutput)[0];
execFileSync("tar", ["xzf", filename], { cwd: tmpDir });
const proto = fs.readFileSync(path.join(tmpDir, "package", "configs.proto"), "utf8");
fs.rmSync(tmpDir, { recursive: true, force: true });

const toCamelCase = (name) => name.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

const messages = {};
const enums = {};
// Each stack entry is { kind: "message" | "enum" | "oneof", name }
const stack = [];
let pendingDoc = [];

const scopeName = () => stack.filter((s) => s.kind !== "oneof").map((s) => s.name).join(".");
const currentMessage = () => [...stack].reverse().find((s) => s.kind !== "oneof");

for (const rawLine of proto.split("\n")) {
    const line = rawLine.trim();
    if (line.startsWith("//")) {
        pendingDoc.push(line.replace(/^\/\/\s?/, ""));
        continue;
    }
    if (line === "") {
        pendingDoc = [];
        continue;
    }
    const doc = pendingDoc.join(" ").replace(/\s+/g, " ").trim();
    pendingDoc = [];

    const block = line.match(/^(message|enum|oneof)\s+(\w+)\s*\{(.*)$/);
    if (block) {
        const [, kind, name, rest] = block;
        stack.push({ kind, name });
        if (kind === "message") {
            messages[scopeName()] = [];
        } else if (kind === "enum") {
            enums[scopeName()] = [];
        }
        if (rest.includes("}")) {
            stack.pop();
        }
        continue;
    }
    if (line.startsWith("}")) {
        stack.pop();
        continue;
    }

    const top = stack[stack.length - 1];
    if (!top) {
        continue;
    }
    if (top.kind === "enum") {
        const value = line.match(/^(\w+)\s*=\s*\d+/);
        if (value) {
            enums[scopeName()].push({ name: value[1], doc });
        }
        continue;
    }
    const field = line.match(/^(optional\s+|repeated\s+)?(map<\s*\w+\s*,\s*[\w.]+\s*>|[\w.]+)\s+(\w+)\s*=\s*\d+/);
    if (field && currentMessage()) {
        const [, modifier, type, name] = field;
        messages[scopeName()].push({
            name: toCamelCase(name),
            type: type.startsWith("map<") ? "map" : type,
            repeated: modifier?.trim() === "repeated",
            doc,
        });
    }
}

const header = `// GENERATED FILE - DO NOT EDIT.
// Generated by scripts/generate-config-schema.mjs from @dataform/core@${version} configs.proto.
// Regenerate with: npm run generate:config-schema
`;

const body = `
export interface ProtoField {
    name: string;
    /** Proto scalar type, a message/enum name, or "map" for map<string, string> fields. */
    type: string;
    repeated: boolean;
    doc: string;
}

export interface ProtoEnumValue {
    name: string;
    doc: string;
}

export const CONFIG_SCHEMA_CORE_VERSION = ${JSON.stringify(version)};

export const protoMessages: Record<string, ProtoField[]> = ${JSON.stringify(messages, null, 4)};

export const protoEnums: Record<string, ProtoEnumValue[]> = ${JSON.stringify(enums, null, 4)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, header + body);
console.log(`Wrote ${path.relative(repoRoot, outFile)} from @dataform/core@${version}`);
